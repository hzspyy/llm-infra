# Only the 40 chapters present at review start; 5.10 is concurrently authored.
paths = [p for p in sorted((ROOT / "src").glob("*/*.md"))
         if p.name.split("-", 1)[0] in EDITS or p.name.startswith("5.5-")]
protected = re.compile(r"(^```[^\n]*\n.*?^```[^\n]*$|<svg\b.*?</svg>)", re.M | re.S)
report = {"files": [], "unmatched": []}
for path in paths:
    original = path.read_text()
    text = original
    ident = path.name.split("-", 1)[0]
    parts = protected.split(text)
    applied = []
    for old, new in COMMON + EDITS.get(ident, []):
        count = sum(p.count(old) for i, p in enumerate(parts) if i % 2 == 0)
        if count:
            parts = [p.replace(old, new) if i % 2 == 0 else p for i, p in enumerate(parts)]
            applied.append({"old": old, "count": count})
        elif (old, new) in EDITS.get(ident, []):
            report["unmatched"].append({"chapter": ident, "old": old})
    text = "".join(parts)
    # Repair old source range syntax; do not touch raw code/output.
    text, directives = re.subn(r"(?m)^(\{\{src(?:fold)?:[^:{}]+):([0-9]+):([0-9]+)(\}\})$", r"\1:\2-\3\4", text)
    # Reader commands, not login/session setup. Historical raw results remain intact.
    text, commands = re.subn(
        r"(?m)^ssh crater 'source /scratch/learn/env\.sh && cd /scratch/learn/work/(labs/L\d+) && /scratch/learn/envs/serve/bin/python ([^'\n]+)'$",
        r"# 在项目根目录、匹配版本的独立环境中运行\npython \1/\2", text)
    if text != original:
        path.write_text(text)
    report["files"].append({"path": str(path.relative_to(ROOT)), "changed": text != original,
                            "edits": applied, "directives": directives, "commands": commands})
(ROOT / "outputs/review-text-pass.json").write_text(json.dumps(report, ensure_ascii=False, indent=2))
print(json.dumps({"reviewed_files": len(paths), "changed_files": sum(x["changed"] for x in report["files"]),
                  "unmatched": report["unmatched"]}, ensure_ascii=False, indent=2))
