from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]

def file(ident):
    matches = list((ROOT / 'src').glob(f'*/{ident}-*.md'))
    assert len(matches) == 1, ident
    return matches[0]

def replace(ident, old, new):
    p = file(ident); t = p.read_text()
    if old not in t:
        raise ValueError((ident, old[:100]))
    p.write_text(t.replace(old, new))

def section(ident, start, end, content):
    p=file(ident); t=p.read_text(); a=t.index(start); b=t.index(end,a)
    p.write_text(t[:a]+content.rstrip()+'\n\n'+t[b:])

